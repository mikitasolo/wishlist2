import { describe, it, expect, vi, beforeEach } from 'vitest';
import { NextRequest } from 'next/server';
import sharp from 'sharp';

// The real sharp runs here: these tests exercise the route's image processing,
// not a stand-in. Storage, the session and the quota lookup are mocked.
const { put } = vi.hoisted(() => ({ put: vi.fn() }));
vi.mock('@vercel/blob', () => ({ put }));
vi.mock('@/lib/auth', () => ({ auth: vi.fn() }));
vi.mock('@/lib/utils/blob', () => ({
  USER_UPLOAD_QUOTA_BYTES: 100 * 1024 * 1024,
  getUserUploadBytes: vi.fn().mockResolvedValue(0),
}));

import { auth } from '@/lib/auth';
import { POST } from '@/app/api/upload/route';

const session = vi.mocked(auth) as unknown as ReturnType<typeof vi.fn>;
const USER_ID = '64b7f0c2a1b2c3d4e5f60718';

function uploadRequest(data: Buffer, type: string, name: string) {
  const form = new FormData();
  form.append('file', new File([new Uint8Array(data)], name, { type }));
  return new NextRequest('http://localhost/api/upload', { method: 'POST', body: form });
}

/** A small, benign image generated by sharp itself (no third-party fixtures). */
function solidImage() {
  return sharp({ create: { width: 8, height: 8, channels: 3, background: '#5e5ce6' } });
}

beforeEach(() => {
  put.mockReset();
  put.mockImplementation(async (pathname: string) => ({
    url: `https://store.public.blob.vercel-storage.com/${pathname}`,
  }));
  session.mockReset();
  session.mockResolvedValue({ user: { id: USER_ID } });
});

describe('POST /api/upload', () => {
  it('refuses an anonymous upload before touching the file', async () => {
    session.mockResolvedValue(null);
    const png = await solidImage().png().toBuffer();

    const res = await POST(uploadRequest(png, 'image/png', 'a.png'));

    expect(res.status).toBe(401);
    expect(put).not.toHaveBeenCalled();
  });

  // regression: the route's module imports sharp, and on Vercel sharp's
  // native libvips was missing from the bundle (WIS-156), so every request
  // to /api/upload failed with a 500. This runs the real sharp end to end;
  // `npm run check:trace` checks libvips ships with the route.
  it('re-encodes a PNG with the real sharp, dropping its EXIF, and stores it under the uploader', async () => {
    const withExif = await solidImage()
      .withExif({ IFD0: { Copyright: 'secret-gps-and-camera-data' } })
      .png()
      .toBuffer();
    expect((await sharp(withExif).metadata()).exif).toBeDefined();

    const res = await POST(uploadRequest(withExif, 'image/png', 'a.png'));

    expect(res.status).toBe(200);
    const [pathname, stored, options] = put.mock.calls[0]!;
    expect(pathname).toBe(`uploads/${USER_ID}/image.png`);
    expect(options).toMatchObject({ contentType: 'image/png', access: 'public' });
    const meta = await sharp(stored as Buffer).metadata();
    expect(meta.format).toBe('png');
    expect(meta.exif).toBeUndefined();
    expect(await res.json()).toEqual({ success: true, url: expect.stringContaining(pathname) });
  });

  // A sharp bump for its libheif advisory (WIS-140) must leave AVIF uploads as
  // they were: accepted, re-encoded as AVIF, metadata dropped.
  it('accepts a benign AVIF, re-encodes it as AVIF and drops its EXIF', async () => {
    const avif = await solidImage()
      .withExif({ IFD0: { Copyright: 'wishlist test fixture' } })
      .avif()
      .toBuffer();
    // The fixture really is an AVIF with EXIF, or the assertions below prove nothing.
    const before = await sharp(avif).metadata();
    expect(before).toMatchObject({ format: 'heif', compression: 'av1' });
    expect(before.exif).toBeDefined();

    const res = await POST(uploadRequest(avif, 'image/avif', 'a.avif'));

    expect(res.status).toBe(200);
    const [pathname, stored, options] = put.mock.calls[0]!;
    expect(pathname).toBe(`uploads/${USER_ID}/image.avif`);
    expect(options).toEqual({ access: 'public', addRandomSuffix: true, contentType: 'image/avif' });
    // Re-encoded, not passed through: still an 8×8 AVIF, but with the EXIF gone.
    expect(Buffer.compare(stored as Buffer, avif)).not.toBe(0);
    const after = await sharp(stored as Buffer).metadata();
    expect(after).toMatchObject({ format: 'heif', compression: 'av1', width: 8, height: 8 });
    expect(after.exif).toBeUndefined();
  });

  it('answers 400, not 500, for bytes sharp cannot decode', async () => {
    const res = await POST(uploadRequest(Buffer.from('not an image'), 'image/png', 'a.png'));

    expect(res.status).toBe(400);
    expect(put).not.toHaveBeenCalled();
  });
});
