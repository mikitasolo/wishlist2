#!/usr/bin/env node
// Builds the bookmarklet's code (lib/bookmarklet/code.ts) from
// lib/bookmarklet/main.ts (WIS-367).
//
//   npm run generate:bookmarklet
//
// The entry plus the product extractor are bundled into one minified,
// self-contained IIFE with a placeholder where the app origin goes; the
// Settings card fills it in from `window.location.origin`, so the same build
// serves production, staging and local dev with no build-time env. It's
// committed rather than built per deploy: rerun this whenever
// lib/bookmarklet/** or lib/utils/productExtract.ts / productFragment.ts
// change; test/unit/bookmarklet.test.ts fails until the two match. A bookmark
// is a frozen copy, so a fix reaches people only when they reinstall it.
import { rolldown } from 'rolldown';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const OUT = 'lib/bookmarklet/code.ts';

/** The minified IIFE, with the origin still a placeholder. */
export async function buildBookmarkletCode() {
  const bundle = await rolldown({
    input: `${root}lib/bookmarklet/main.ts`,
    resolve: { alias: { '@': root.replace(/\/$/, '') } },
    logLevel: 'silent',
  });
  const { output } = await bundle.generate({
    format: 'iife',
    minify: true,
    codeSplitting: false,
  });
  await bundle.close();
  return output[0].code.trim();
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const code = await buildBookmarkletCode();
  writeFileSync(
    OUT,
    `// Generated by \`npm run generate:bookmarklet\` (scripts/build-bookmarklet.mjs)
// from lib/bookmarklet/main.ts. Don't edit it by hand: rerun the script.
// test/unit/bookmarklet.test.ts fails when this no longer matches the source.

/** The bookmarklet's script, its app origin still \`APP_ORIGIN_PLACEHOLDER\`. */
export const BOOKMARKLET_CODE =
  ${JSON.stringify(code)};
`
  );
  console.log(`${OUT}: ${code.length} bytes`);
}
