#!/usr/bin/env node
// Renders the email header's logo (lib/emailLogo.ts) from app/icon.svg (WIS-208).
//
//   npm run generate:email-logo
//
// Email clients render SVG poorly and block remote images by default, so every
// email carries the logo as an inline PNG attachment. It's rendered here, once,
// and committed, rather than with sharp on the first send: sharp then has no
// part in sending an email, so sign-in (the magic link) can't fail on it
// (WIS-156), and nothing in the app needs sharp's SVG loader but next/og.
// Rerun this whenever app/icon.svg changes; test/unit/emailLogo.test.ts fails
// until the two match.
import sharp from 'sharp';
import { readFileSync, writeFileSync } from 'node:fs';

/** 2x for retina: the email header draws the logo at 48px. */
const SIZE = 96;
const SOURCE = 'app/icon.svg';
const OUT = 'lib/emailLogo.ts';

// sharp draws an SVG at the size it's resized to, so the edges stay crisp.
const png = await sharp(readFileSync(SOURCE))
  .resize(SIZE, SIZE)
  .png({ compressionLevel: 9 })
  .toBuffer();

writeFileSync(
  OUT,
  `// Generated by \`npm run generate:email-logo\` (scripts/generate-email-logo.mjs)
// from ${SOURCE}. Don't edit it by hand: rerun the script when the logo changes.
// test/unit/emailLogo.test.ts fails when this no longer matches ${SOURCE}.

/** The brand logo as a ${SIZE}×${SIZE} PNG, base64-encoded, for the email header. */
export const EMAIL_LOGO_PNG_BASE64 =
  '${png.toString('base64')}';
`
);
console.log(`${OUT}: ${SIZE}×${SIZE} PNG, ${png.length} bytes`);
